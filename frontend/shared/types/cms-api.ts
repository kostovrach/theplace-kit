import type { Query } from '@directus/sdk';

/**
 * Унифицированный формат ответа CMS API.
 *
 * Используется всеми CMS endpoint'ами для приведения успешных
 * и ошибочных ответов к единой структуре.
 *
 * @template T - Тип данных, содержащихся в поле `data`.
 * По умолчанию используется `unknown`.
 */
export interface CmsResponse<T = unknown> {
    /**
     * Флаг успешного выполнения операции.
     */
    success: boolean;

    /**
     * HTTP-код ответа.
     */
    status: number;

    /**
     * Данные, возвращённые CMS.
     *
     * Содержит результат операции при успешном запросе
     * или `null`,если данные отсутствуют.
     */
    data: T | null;

    /**
     * Сообщение с результатом выполнения операции.
     */
    message: string;
}

/**
 * Query-параметры контракта CMS API.
 *
 * Описывает набор параметров, поддерживаемых endpoint'ами CMS
 * для фильтрации, сортировки, пагинации и управления составом
 * возвращаемых данных.
 *
 * Для параметров, зависящих от структуры конкретной коллекции,
 * используется максимально широкий совместимый вариант типа
 * {@link Query} из `@directus/sdk`, поскольку на момент разбора
 * query-параметров конкретная коллекция ещё может быть неизвестна.
 */
export interface CmsQuery {
    /**
     * Поля, которые должны быть включены в ответ.
     *
     * Поддерживает строковый и массивный синтаксис Directus,
     * включая указание вложенных relational-полей.
     *
     * @example
     * '?fields=id,title,status'
     *
     * @example
     * '?fields=["id","title",{"author":["name"]}]'
     */
    fields?: Query<Schema, Schema[keyof Schema]>['fields'] | readonly string[];

    /**
     * Фильтр для получаемых данных.
     *
     * Использует синтаксис фильтров Directus и может содержать
     * вложенные условия и логические операторы.
     *
     * @example
     * '?filter={"status":{"_eq":"published"}}'
     */
    filter?: Query<Schema, Schema[keyof Schema]>['filter'];

    /**
     * Порядок сортировки возвращаемых данных.
     *
     * Префикс `-` перед именем поля означает сортировку по убыванию.
     * Для нескольких полей поддерживается строковый и массивный синтаксис.
     *
     * @example
     * '?sort=-date_created,title'
     *
     * @example
     * '?sort=["-date_created","title"]'
     */
    sort?: Query<Schema, Schema[keyof Schema]>['sort'] | readonly string[];

    /**
     * Максимальное количество элементов в ответе.
     *
     * Применяется для regular-коллекций.
     *
     * Положительное значение ограничивает количество возвращаемых
     * элементов, значение `-1` используется для снятия ограничения,
     * если это разрешено конфигурацией Directus.
     */
    limit?: number;

    /**
     * Количество элементов, которые необходимо пропустить
     * перед формированием ответа.
     *
     * Используется для offset-based пагинации.
     */
    offset?: number;

    /**
     * Номер страницы при использовании page-based пагинации.
     *
     * При использовании совместно с `limit` соответствующее значение
     * `offset` рассчитывается по формуле:
     *
     * `offset = (page - 1) * limit`
     *
     * Если одновременно переданы `page` и `offset`, приоритет имеет `offset`.
     */
    page?: number;

    /**
     * Глобальный текстовый поиск по доступным для поиска полям
     * коллекции и поддерживаемым связанным данным.
     *
     * @example
     * '?search=FooBar'
     */
    search?: string;

    /**
     * Параметры запросов для глубокой вложенности relational-данных.
     *
     * Позволяет независимо задавать параметры фильтрации и другие
     * настройки для вложенных relational-полей.
     *
     * @example
     * '?deep={"translations":{"_filter":{"languages_code":{"_eq":"ru"}}}}'
     */
    deep?: Query<Schema, Schema[keyof Schema]>['deep'];
}
