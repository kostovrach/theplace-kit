/**
 * Нормализует номер телефона к единому российскому формату.
 *
 * Функция удаляет из входного значения все символы, кроме цифр,
 * после чего приводит номер к формату из 11 цифр с ведущей `7`.
 *
 * Поддерживаются следующие варианты:
 * - `+7 (888) 777-66-55` => `78887776655`;
 * - `8 (888) 777-66-55`  => `78887776655`;
 * - `+78887776655`       => `78887776655`;
 * - `8887776655`         => `78887776655`.
 *
 * Номер с ведущей `8` преобразуется в международное представление
 * с заменой `8` на `7`. Номер из 10 цифр интерпретируется как
 * российский номер без кода страны и получает ведущую `7`.
 *
 * Функция проверяет только структуру номера: после очистки должно
 * получиться либо 10 цифр, либо 11 цифр с ведущей `7` или `8`.
 * **Проверка существования номера и соответствия конкретному диапазону российской нумерации не выполняется**.
 *
 * @param raw - Номер телефона в строковом или числовом представлении.
 * Может содержать пробелы, скобки, дефисы и другие нечисловые символы.
 *
 * @returns Номер телефона в виде строки из 11 цифр с ведущей `7` или пустую строку, в случае, если передано невалидное значение.
 */
export const normalizePhone = (raw: string | number): string => {
    const digits = String(raw).replace(/\D/g, '');

    if (digits.startsWith('8') && digits.length === 11) {
        return '7' + digits.slice(1);
    }

    if (digits.startsWith('7') && digits.length === 11) {
        return digits;
    }

    if (digits.length === 10) {
        return '7' + digits;
    }

    return '';
};
