/**
 * Система единиц измерения размера файла.
 *
 * - `SI`  - десятичная система, где 1 kB = 1000 байт;
 * - `IEC` - двоичная система, где 1 kB = 1024 байта.
 *
 * @internal
 */
type FileSizeBase = 'SI' | 'IEC';

/**
 * Форматирование байтового значения в человеко-читаемый вид.
 *
 * В зависимости от выбранной системы измерения функция использует
 * соответствующий коэффициент:
 *
 * - `SI`  - 1000 байт на единицу;
 * - `IEC` - 1024 байта на единицу.
 *
 * Поддерживаются единицы `kB`, `MB` и `GB`. Размер выбирается по
 * наибольшей подходящей единице из этого диапазона.
 *
 * Значение округляется до одного знака после запятой. Если результат
 * округления не содержит дробной части, лишние нули удаляются.
 *
 * Пример:
 *
 * - `1200`    => `1.2 kB` в системе `SI`;
 * - `1024`    => `1 kB` в системе `IEC`;
 * - `1500000` => `1.5 MB` в системе `SI`.
 *
 * Если переданное значение невозможно преобразовать в конечное число,
 * равно нулю или является отрицательным, функция возвращает `0 kB`.
 *
 * @param raw - Размер файла в байтах в виде числа или числовой строки.
 * @param base - Система измерения размера:
 * `SI` использует множитель 1000, `IEC` - 1024.
 * По умолчанию используется `SI`.
 *
 * @returns Отформатированный размер файла в виде строки
 * `<значение> <единица>`, например `1.2 MB`.
 */
export function normalizeBytes(raw: string | number, base: FileSizeBase = 'SI'): string {
    const bytes = Number(raw);
    if (!Number.isFinite(bytes) || bytes <= 0) return '0 kB';

    const step = base === 'SI' ? 1000 : 1024;

    const units = [
        { unit: 'GB', value: step ** 3 },
        { unit: 'MB', value: step ** 2 },
        { unit: 'kB', value: step },
    ];

    const match = units.find((u) => bytes >= u.value) ?? units[units.length - 1];

    if (!match) return '0 kB';

    const size = bytes / match.value;

    return `${parseFloat(size.toFixed(1))} ${match.unit}`;
}
